import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const proofFilePath = process.env.TERMKIT_ACCEPTANCE_PROOF_FILE ?? 'acceptance-proof.local.json';
const notesFilePath = process.env.TERMKIT_MICROSOFT_INTERACTIVE_NOTES_FILE?.trim();
const notesFromEnv = process.env.TERMKIT_MICROSOFT_INTERACTIVE_NOTES?.trim();
const timestamp = new Date().toISOString();
const commit = currentCommit();
const proofFileExists = existsSync(proofFilePath);
const proofFile = loadProofFile(proofFilePath);
const requiredFragments = ['allowed-domain', 'blocked-domain', 'admin-email', 'local login'];

if (proofFileExists && proofFile.commit !== commit) {
	console.error(
		`Proof file ${proofFilePath} targets ${proofFile.commit ?? '<missing>'}, but current HEAD is ${commit}. Regenerate or refresh the proof file before recording Microsoft interactive proof.`
	);
	process.exit(1);
}

const notes = readNotes();
const missingFragments = requiredFragments.filter(
	(fragment) => !notes.toLowerCase().includes(fragment)
);

if (missingFragments.length > 0) {
	console.error(
		`Microsoft interactive proof notes are missing required fragment(s): ${missingFragments.join(', ')}`
	);
	process.exit(1);
}

const forbiddenPattern = forbiddenSecretPattern(notes);
if (forbiddenPattern) {
	console.error(
		`Microsoft interactive proof notes look like they include sensitive material (${forbiddenPattern}); proof file was not updated.`
	);
	process.exit(1);
}

const placeholderPattern = placeholderProofPattern(notes);
if (placeholderPattern) {
	console.error(
		`Microsoft interactive proof notes still look like a template placeholder (${placeholderPattern}); proof file was not updated.`
	);
	process.exit(1);
}

proofFile.commit = commit;
proofFile.generatedAt ??= timestamp;
proofFile.proofs ??= {};
proofFile.proofs.microsoftInteractive = {
	passed: true,
	timestamp,
	command: 'manual browser acceptance',
	instructions:
		'Generated by npm run acceptance:record-microsoft-interactive after operator notes passed local validation. Keep notes redacted; do not add tenant secrets, authorization codes, access tokens, refresh tokens, ID tokens, or cookies.',
	redactedEnv: [
		'MICROSOFT_TENANT_ID',
		'MICROSOFT_CLIENT_ID',
		'MICROSOFT_ALLOWED_DOMAINS',
		'MICROSOFT_ADMIN_EMAILS'
	],
	notes,
	output: ''
};

writeFileSync(proofFilePath, `${JSON.stringify(proofFile, null, 2)}\n`);
console.log(`Recorded Microsoft interactive proof in ${proofFilePath}.`);

function readNotes() {
	if (notesFilePath && notesFromEnv) {
		console.error(
			'Set either TERMKIT_MICROSOFT_INTERACTIVE_NOTES_FILE or TERMKIT_MICROSOFT_INTERACTIVE_NOTES, not both.'
		);
		process.exit(1);
	}

	if (notesFilePath) {
		if (!existsSync(notesFilePath)) {
			console.error(`Microsoft interactive notes file does not exist: ${notesFilePath}`);
			process.exit(1);
		}
		const notes = readFileSync(notesFilePath, 'utf8').trim();
		return requireNotes(notes);
	}

	return requireNotes(notesFromEnv ?? '');
}

function requireNotes(notes) {
	if (!notes) {
		console.error(
			'Set TERMKIT_MICROSOFT_INTERACTIVE_NOTES or TERMKIT_MICROSOFT_INTERACTIVE_NOTES_FILE with redacted manual browser proof notes.'
		);
		process.exit(1);
	}
	return notes;
}

function forbiddenSecretPattern(value) {
	const checks = [
		[/\bpassword\b/i, 'password label'],
		[
			/\b(access_token|refresh_token|id_token|client_secret|authorization:\s*bearer|set-cookie|cookie:)\b/i,
			'secret, token, or cookie label'
		],
		[/[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}\.[A-Za-z0-9_-]{20,}/, 'JWT-like value']
	];

	for (const [pattern, label] of checks) {
		if (pattern.test(value)) return label;
	}

	return null;
}

function placeholderProofPattern(value) {
	const checks = [
		[/\bTODO\b/i, 'TODO marker'],
		[/replace with redacted proof/i, 'template instruction'],
		[/\.\.\./, 'ellipsis placeholder']
	];

	for (const [pattern, label] of checks) {
		if (pattern.test(value)) return label;
	}

	return null;
}

function loadProofFile(path) {
	if (!existsSync(path)) {
		return { commit, generatedAt: timestamp, proofs: {} };
	}

	try {
		const parsed = JSON.parse(readFileSync(path, 'utf8'));
		if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
			throw new Error('proof file root must be an object');
		}
		return parsed;
	} catch (error) {
		console.error(`Could not read acceptance proof file ${path}: ${errorText(error)}`);
		process.exit(1);
	}
}

function currentCommit() {
	try {
		return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
	} catch {
		return '<commit-sha>';
	}
}

function errorText(error) {
	return error instanceof Error ? error.message : String(error);
}
