import { spawnSync, execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const proofFilePath = process.env.TERMIXKIT_ACCEPTANCE_PROOF_FILE ?? 'acceptance-proof.local.json';
const timestamp = new Date().toISOString();
const commit = currentCommit();
const proofFileExists = existsSync(proofFilePath);
const proofFile = loadProofFile(proofFilePath);

if (proofFileExists && proofFile.commit !== commit) {
	console.error(
		`Proof file ${proofFilePath} targets ${proofFile.commit ?? '<missing>'}, but current HEAD is ${commit}. Regenerate or refresh the proof file before recording Microsoft smoke proof.`
	);
	process.exit(1);
}

const env = {
	...process.env,
	TERMIXKIT_SMOKE_MICROSOFT_REQUIRE_REAL: '1'
};

const result = spawnSync('npm', ['run', 'smoke:microsoft'], {
	cwd: process.cwd(),
	env,
	encoding: 'utf8'
});
const output = joinOutput(result.stdout, result.stderr);

if (output) process.stdout.write(`${output}\n`);

if (result.status !== 0) {
	console.error('Microsoft smoke did not pass; proof file was not updated.');
	process.exit(result.status ?? 1);
}

if (!output.includes('[pass] Microsoft Entra discovery and JWKS')) {
	console.error('Real Microsoft discovery did not pass; proof file was not updated.');
	process.exit(1);
}

if (output.includes('[skip] Microsoft Entra discovery and JWKS')) {
	console.error('Real Microsoft discovery was skipped; proof file was not updated.');
	process.exit(1);
}

if (
	process.env.TERMIXKIT_SMOKE_MICROSOFT_CLIENT_CREDENTIALS_SCOPE?.trim() &&
	!output.includes('[pass] Microsoft Entra client credentials')
) {
	console.error('Microsoft client credentials smoke was requested but did not pass.');
	process.exit(1);
}

proofFile.commit = commit;
proofFile.generatedAt ??= timestamp;
proofFile.proofs ??= {};
proofFile.proofs.microsoftSmoke = {
	passed: true,
	timestamp,
	command: proofCommand(),
	instructions:
		'Generated by npm run acceptance:record-microsoft-smoke after the real Microsoft smoke passed. Do not add tenant secrets, authorization codes, access tokens, refresh tokens, ID tokens, or cookies.',
	redactedEnv: [
		'MICROSOFT_AUTH_ENABLED',
		'MICROSOFT_TENANT_ID',
		'MICROSOFT_CLIENT_ID',
		'MICROSOFT_CLIENT_SECRET',
		'MICROSOFT_ALLOWED_DOMAINS',
		'MICROSOFT_ADMIN_EMAILS'
	],
	output
};

writeFileSync(proofFilePath, `${JSON.stringify(proofFile, null, 2)}\n`);
console.log(`Recorded Microsoft smoke proof in ${proofFilePath}.`);

function proofCommand() {
	const scope = process.env.TERMIXKIT_SMOKE_MICROSOFT_CLIENT_CREDENTIALS_SCOPE?.trim();
	if (!scope) return 'TERMIXKIT_SMOKE_MICROSOFT_REQUIRE_REAL=1 npm run smoke:microsoft';
	return 'TERMIXKIT_SMOKE_MICROSOFT_REQUIRE_REAL=1 TERMIXKIT_SMOKE_MICROSOFT_CLIENT_CREDENTIALS_SCOPE=<redacted> npm run smoke:microsoft';
}

function loadProofFile(path) {
	if (!existsSync(path)) {
		return { commit, generatedAt: timestamp, proofs: {} };
	}

	try {
		const parsed = JSON.parse(readFileSync(path, 'utf8'));
		if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
			throw new Error('proof file root must be an object');
		}
		return parsed;
	} catch (error) {
		console.error(`Could not read acceptance proof file ${path}: ${errorText(error)}`);
		process.exit(1);
	}
}

function currentCommit() {
	try {
		return execFileSync('git', ['rev-parse', 'HEAD'], { encoding: 'utf8' }).trim();
	} catch {
		return '<commit-sha>';
	}
}

function joinOutput(stdout, stderr) {
	return [stdout, stderr]
		.map((value) => value?.trim())
		.filter(Boolean)
		.join('\n');
}

function errorText(error) {
	return error instanceof Error ? error.message : String(error);
}
